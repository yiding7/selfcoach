"""人体肌群热力图。

正面 + 背面两张解剖示意图，每个肌群一个独立图形，按本周训练量着色。
颜色一律走 CSS class，不写死 —— 深浅色模式自动跟随。

画法上的两个约定：

1. **左右对称的肌群只写右半边**，左半边用 `translate(2*CX,0) scale(-1,1)`
   镜像出来。手写两遍必然会不对称，而且改一边忘一边。
2. **一个肌群可以由多块组成**（比如腹直肌的六块、背部的斜方 + 背阔）。
   同一个 `<g class="muscle">` 里的每块都会被描边，块与块之间自然形成分隔，
   不需要额外画分隔线。

形状按真实肌肉走向画（胸大肌呈扇形、背阔肌呈 V 形收束、股四头肌上宽下窄），
但不追求解剖精度 —— 这是「这周练了哪儿」的示意图，一眼能看懂哪块颜色深最重要。
"""

