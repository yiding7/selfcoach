def _mirror(shapes: str) -> str:
    """把右半边镜像到左半边。"""
    return f'<g transform="translate({VIEW_W},0) scale(-1,1)">{shapes}</g>'


def _sym(shapes: str) -> str:
    """左右都要的肌群：右半边 + 它的镜像。"""
    return shapes + _mirror(shapes)


def _p(d: str) -> str:
    return f'<path d="{d}"/>'


